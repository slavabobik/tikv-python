"""Regenerate the protobuf modules in ``src/tikv/_proto`` from ``proto/``.

Usage::

    uv run --with 'grpcio-tools==1.62.3' python scripts/generate_protos.py

The generator version is pinned deliberately: code generated by an older
``protoc`` runs on every newer protobuf runtime, while code generated by a
recent one refuses to import on older runtimes.  Bumping it raises the minimum
``protobuf`` version our users need, so do it only on purpose.
"""

from __future__ import annotations

import re
import shutil
import sys
from pathlib import Path

from grpc_tools import protoc

ROOT = Path(__file__).resolve().parent.parent
PROTO_DIR = ROOT / "proto"
OUT_DIR = ROOT / "src" / "tikv" / "_proto"

HEADER = "# Generated by scripts/generate_protos.py. DO NOT EDIT.\n"


def main() -> int:
    protos = sorted(PROTO_DIR.glob("*.proto"))
    if OUT_DIR.exists():
        shutil.rmtree(OUT_DIR)
    OUT_DIR.mkdir(parents=True)

    args = [
        "protoc",
        f"--proto_path={PROTO_DIR}",
        f"--python_out={OUT_DIR}",
        f"--pyi_out={OUT_DIR}",
        *map(str, protos),
    ]
    if protoc.main(args) != 0:
        print("protoc failed", file=sys.stderr)
        return 1

    modules = [p.stem + "_pb2" for p in protos]
    pattern = re.compile(rf"^import ({'|'.join(modules)})\b", re.MULTILINE)
    for path in sorted(OUT_DIR.glob("*_pb2.py*")):
        source = pattern.sub(r"from . import \1", path.read_text())
        path.write_text(HEADER + source)

    (OUT_DIR / "__init__.py").write_text(
        HEADER + '"""Protobuf messages for the TiKV and PD wire protocols."""\n'
    )
    print(f"generated {len(modules)} modules into {OUT_DIR.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
